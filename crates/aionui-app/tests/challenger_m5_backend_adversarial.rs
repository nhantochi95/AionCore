// SECTION 3: 100% HARD FUSE BEHAVIOR & DUAL WALLET
// ===========================================================================

#[tokio::test]
async fn challenge_dual_wallet_exact_boundaries_and_hard_fuse() {
    let db = init_database_memory().await.unwrap();
    let repo = SqliteCustomBridgeRepository::new(db.pool().clone());
    let user_id = "user_hard_fuse_boundaries";

    // Set budget limit to $100.00
    let initial_wallet = repo.update_budget_limit(user_id, 100.0).await.unwrap();
    assert_eq!(initial_wallet.api_key_budget_limit_usd, 100.0);
    assert_eq!(initial_wallet.api_key_spent_usd, 0.0);

    // Step 1: Spend $79.99 (79.99% of $100.00) -> NO soft warning, NO hard block
    let (w1, soft1, hard1) = repo
        .record_cost_run(RecordCostRunParams {
            owner_user_id: user_id.into(),
            run_id: "run-79.99".into(),
            team_id: "team-test".into(),
            agent_id: "gpt-4".into(),
            wallet_type: "api_key".into(),
            tokens_input: 100_000,
            tokens_output: 10_000,
            cost_usd: 79.99,
        })
        .await
        .unwrap();

    assert!(!soft1, "At 79.99% soft warning must NOT trigger");
    assert!(!hard1, "At 79.99% hard block must NOT trigger");
    assert_eq!(w1.soft_warning_triggered, 0);
    assert_eq!(w1.hard_block_triggered, 0);

    let inbox_cards = repo.list_action_inbox_items(user_id, None).await.unwrap();
    assert_eq!(inbox_cards.len(), 0, "No inbox cards expected at 79.99%");

    // Step 2: Spend $0.01 (exact 80.00% boundary: $80.00 of $100.00) -> SOFT WARNING TRIPS
    let (w2, soft2, hard2) = repo
        .record_cost_run(RecordCostRunParams {
            owner_user_id: user_id.into(),
            run_id: "run-80.00".into(),
            team_id: "team-test".into(),
            agent_id: "gpt-4".into(),
            wallet_type: "api_key".into(),
            tokens_input: 100,
            tokens_output: 10,
            cost_usd: 0.01,
        })
        .await
        .unwrap();

    assert!(soft2, "At exact 80.00% soft warning MUST trigger");
    assert!(!hard2, "At 80.00% hard block must NOT trigger");
    assert_eq!(w2.soft_warning_triggered, 1);
    assert_eq!(w2.hard_block_triggered, 0);

    let inbox_cards = repo.list_action_inbox_items(user_id, None).await.unwrap();
    assert_eq!(inbox_cards.len(), 1, "Exactly 1 soft warning inbox card expected");
    assert_eq!(inbox_cards[0].category, "budget_warning");

    // Step 3: Spend $19.99 (reaching $99.99, 99.99%) -> NO DUPLICATE SOFT WARNING, NO HARD BLOCK
    let (w3, soft3, hard3) = repo
        .record_cost_run(RecordCostRunParams {
            owner_user_id: user_id.into(),
            run_id: "run-99.99".into(),
            team_id: "team-test".into(),
            agent_id: "gpt-4".into(),
            wallet_type: "api_key".into(),
            tokens_input: 20_000,
            tokens_output: 2_000,
            cost_usd: 19.99,
        })
        .await
        .unwrap();

    assert!(!soft3, "Duplicate soft warning must be suppressed (newly_soft = false)");
    assert!(!hard3, "At 99.99% hard block must NOT trigger");
    assert_eq!(w3.soft_warning_triggered, 1);
    assert_eq!(w3.hard_block_triggered, 0);

    let inbox_cards = repo.list_action_inbox_items(user_id, None).await.unwrap();
    assert_eq!(inbox_cards.len(), 1, "Duplicate suppression: still exactly 1 inbox card");

    // Step 4: Spend $0.01 (exact 100.00% boundary: $100.00 of $100.00) -> HARD FUSE TRIPS
    let (w4, soft4, hard4) = repo
        .record_cost_run(RecordCostRunParams {
            owner_user_id: user_id.into(),
            run_id: "run-100.00".into(),
            team_id: "team-test".into(),
            agent_id: "gpt-4".into(),
            wallet_type: "api_key".into(),
            tokens_input: 100,
            tokens_output: 10,
            cost_usd: 0.01,
        })
        .await
        .unwrap();

    assert!(!soft4, "Soft warning already active");
    assert!(hard4, "At exact 100.00% hard fuse MUST trigger (newly_hard = true)");
    assert_eq!(w4.soft_warning_triggered, 1);
    assert_eq!(w4.hard_block_triggered, 1);

    let inbox_cards = repo.list_action_inbox_items(user_id, None).await.unwrap();
    assert_eq!(inbox_cards.len(), 2, "Expected 2 inbox cards (1 soft, 1 hard)");

    // Step 5: Verify CLI Subscription IMMUNITY under hard fuse
    // When hard fuse is tripped, CLI subscription runs MUST succeed at $0.00 and NOT increment spend
    for i in 1..=10 {
        let (w_cli, soft_cli, hard_cli) = repo
            .record_cost_run(RecordCostRunParams {
                owner_user_id: user_id.into(),
                run_id: format!("cli-fuse-immune-{i}"),
                team_id: "team-test".into(),
                agent_id: "claude-code-oauth".into(),
                wallet_type: "cli_subscription".into(),
                tokens_input: 50_000,
                tokens_output: 10_000,
                cost_usd: 0.0,
            })
            .await
            .unwrap();

        assert!(!soft_cli);
        assert!(!hard_cli);
        assert_eq!(w_cli.api_key_spent_usd, 100.0, "CLI runs must never increment api_key_spent_usd");
        assert_eq!(w_cli.cli_subscription_runs_count, i);
        assert_eq!(w_cli.hard_block_triggered, 1, "Hard block remains active for paid agents");
    }

    // Step 6: Dynamic limit adjustment clearing the fuse
    // Increase budget limit to $250.00 ($100 spent / $250 = 40% < 80%)
    let w_raised = repo.update_budget_limit(user_id, 250.0).await.unwrap();
    assert_eq!(w_raised.api_key_budget_limit_usd, 250.0);
    assert_eq!(w_raised.hard_block_triggered, 0, "Hard fuse cleared on budget increase");
    assert_eq!(w_raised.soft_warning_triggered, 0, "Soft warning cleared on budget increase");

    // Step 7: Lower budget limit back down to $90.00 ($100 spent / $90 = 111% > 100%)
    let w_lowered = repo.update_budget_limit(user_id, 90.0).await.unwrap();
    assert_eq!(w_lowered.hard_block_triggered, 1, "Hard fuse re-tripped on budget decrease");
    assert_eq!(w_lowered.soft_warning_triggered, 1, "Soft warning re-tripped on budget decrease");

    // Step 8: Reset wallet
    let w_reset = repo.reset_cost_wallet(user_id).await.unwrap();
    assert_eq!(w_reset.api_key_spent_usd, 0.0);
    assert_eq!(w_reset.cli_subscription_runs_count, 0);
    assert_eq!(w_reset.api_key_runs_count, 0);
    assert_eq!(w_reset.soft_warning_triggered, 0);
    assert_eq!(w_reset.hard_block_triggered, 0);
}
