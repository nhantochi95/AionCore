#[tokio::test(flavor = "multi_thread", worker_threads = 8)]
async fn challenge_atomic_lock_100_concurrent_storm() {
    let db = init_database_memory().await.unwrap();
    let repo = Arc::new(SqliteCustomBridgeRepository::new(db.pool().clone()));
    let user_id = "user_atomic_storm";

    // 1. Create a single action token
    let token = repo
        .create_action_token(
            user_id,
            CustomTargetType::Room,
            "room-adversarial-1",
            "squash_merge",
            &serde_json::json!({"action": "approve"}),
            Some(3600_000),
        )
        .await
        .unwrap();

    // 2. Spawn 100 concurrent tasks racing to consume the EXACT same token
    let mut handles = Vec::new();
    for _ in 0..100 {
        let repo_c = repo.clone();
        let tok = token.clone();
        handles.push(tokio::spawn(async move {
            repo_c.consume_action_token_once(&tok).await
        }));
    }

    let mut true_count = 0;
    let mut false_count = 0;

    for h in handles {
        match h.await.unwrap() {
            Ok(true) => true_count += 1,
            Ok(false) => false_count += 1,
            Err(e) => panic!("Atomic lock query returned DB error: {e}"),
        }
    }

    // ORACLE ASSERTION: Exactly ONE task succeeded in consuming the token!
    assert_eq!(
        true_count, 1,
        "Idempotency violation: Expected exactly 1 success among 100 racers, but got {true_count}!"
    );
    assert_eq!(
        false_count, 99,
        "Idempotency violation: Expected 99 rejections among 100 racers, but got {false_count}!"
    );

    // 3. Sequential replay attempts MUST continue to return false
    for replay_idx in 1..=5 {
        let replayed = repo.consume_action_token_once(&token).await.unwrap();
        assert!(
            !replayed,
            "Replay {replay_idx} must return false on already consumed token"
        );
    }
}

#[tokio::test]
async fn challenge_atomic_lock_expired_and_non_existent_tokens() {
    let db = init_database_memory().await.unwrap();
    let repo = SqliteCustomBridgeRepository::new(db.pool().clone());
    let user_id = "user_token_expiry";

    // 1. Create an expired token (expires_at in the past: 1 ms TTL, sleep 15ms)
    let expired_token = repo
        .create_action_token(
            user_id,
            CustomTargetType::Room,
            "room-expiry",
            "test_action",
            &serde_json::json!({}),
            Some(1), // 1ms
        )
        .await
        .unwrap();

    tokio::time::sleep(tokio::time::Duration::from_millis(15)).await;

    // Must return Ok(false) because expires_at > now is false
    let consumed_expired = repo.consume_action_token_once(&expired_token).await.unwrap();
    assert!(
        !consumed_expired,
        "Expired token must NOT be consumed, must return Ok(false)"
    );

    // 2. Non-existent token
    let non_existent = repo
        .consume_action_token_once("token_never_existed_xyz")
        .await
        .unwrap();
    assert!(
        !non_existent,
        "Non-existent token must return Ok(false)"
    );
}

