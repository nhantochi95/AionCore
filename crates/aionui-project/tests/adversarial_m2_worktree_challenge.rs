use std::path::{Path, PathBuf};
use aionui_project::scm::{
    GitWorktreeEngine, WorktreeConfig, WorktreeError, sanitize_conventional_commit,
};

fn init_test_git_repo(path: &Path) -> git2::Repository {
    let repo = git2::Repository::init(path).expect("failed to init test repo");
    let sig = git2::Signature::now("Challenger", "challenger@teamwork.internal")
        .expect("failed to create signature");

    let readme = path.join("README.md");
    std::fs::write(&readme, "# Base Repository\n").expect("failed to write README");

    let mut index = repo.index().expect("failed to get index");
    index.add_path(Path::new("README.md")).expect("failed to add README");
    let tree_oid = index.write_tree().expect("failed to write tree");

    let commit_oid = {
        let tree = repo.find_tree(tree_oid).expect("failed to find tree");
        repo.commit(Some("HEAD"), &sig, &sig, "chore: initial base commit", &tree, &[])
            .expect("failed to create initial commit")
    };

    {
        let commit = repo.find_commit(commit_oid).expect("failed to find commit");
        repo.branch("feat/hybrid-command-hub", &commit, false)
            .expect("failed to branch feat/hybrid-command-hub");
        repo.set_head("refs/heads/feat/hybrid-command-hub")
            .expect("failed to set HEAD");
    }

    repo
}

/// F09 Test: Dispatch Prompt specific poisoned strings.
/// Explicitly tests:
/// - Co-authored-by: Claude <noreply@anthropic.com>
/// - Generated by GPT-4
/// - 🤖 Generated with Cursor
/// - AI: Assistant
#[test]
fn challenge_f09_dispatch_poisoned_strings() {
    let raw = r#"feat(auth): add passkey authentication

This introduces biometric passkey authentication.

Co-authored-by: Claude <noreply@anthropic.com>
Generated by GPT-4
🤖 Generated with Cursor
AI: Assistant
"#;

    let cleaned = sanitize_conventional_commit(raw, "lease-dispatch-1").expect("sanitize failed");
    println!("Cleaned commit message:\n---\n{}\n---", cleaned);

    let leaks = [
        ("Co-authored-by: Claude", cleaned.contains("Co-authored-by")),
        ("Generated by GPT-4", cleaned.contains("Generated by GPT-4")),
        ("🤖 Generated with Cursor", cleaned.contains("Generated with Cursor") || cleaned.contains("🤖")),
        ("AI: Assistant", cleaned.contains("AI: Assistant")),
    ];

    let any_leaked = leaks.iter().any(|(_, leaked)| *leaked);
    for (tag, leaked) in &leaks {
        if *leaked {
            eprintln!("[LEAK DETECTED] Tag '{}' was NOT stripped!", tag);
        }
    }

    assert!(
        !any_leaked,
        "F09 VIOLATION: Attribution tags leaked into cleaned commit message! Leaks: {:?}",
        leaks
    );
}

