/// F08 Test: Multi-commit worktree squashed into EXACTLY 1 commit on base branch.
#[tokio::test]
async fn challenge_f08_squash_merge_multi_commit_squashing() {
    let temp_dir = tempfile::tempdir().expect("failed to create temp dir");
    let repo_path = temp_dir.path().to_path_buf();
    let primary_repo = init_test_git_repo(&repo_path);

    let engine = GitWorktreeEngine::new();
    let lease_id = "wt-multi-commit-1".to_string();

    let config = WorktreeConfig {
        lease_id: lease_id.clone(),
        repo_path: repo_path.clone(),
        base_branch: "feat/hybrid-command-hub".to_string(),
        room_id: Some("room-multi".to_string()),
        team_id: Some("team-multi".to_string()),
        owner_user_id: "challenger-1".to_string(),
    };

    let row = engine.allocate_worktree(config, None).await.expect("failed to allocate");
    let worktree_dir = PathBuf::from(&row.worktree_path);
    assert!(worktree_dir.exists());

    let wt_repo = git2::Repository::open(&worktree_dir).expect("failed to open worktree");
    let sig = git2::Signature::now("Agent Worker", "agent@internal").unwrap();

    // Commit 1 in worktree
    let file1 = worktree_dir.join("module_a.rs");
    std::fs::write(&file1, "pub fn func_a() -> i32 { 10 }\n").unwrap();
    {
        let mut idx = wt_repo.index().unwrap();
        idx.add_path(Path::new("module_a.rs")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = wt_repo.find_tree(tree_oid).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        wt_repo.commit(Some("HEAD"), &sig, &sig, "feat: commit 1", &tree, &[&head]).unwrap();
    }

    // Commit 2 in worktree
    let file2 = worktree_dir.join("module_b.rs");
    std::fs::write(&file2, "pub fn func_b() -> i32 { 20 }\n").unwrap();
    {
        let mut idx = wt_repo.index().unwrap();
        idx.add_path(Path::new("module_b.rs")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = wt_repo.find_tree(tree_oid).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        wt_repo.commit(Some("HEAD"), &sig, &sig, "feat: commit 2", &tree, &[&head]).unwrap();
    }

    // Commit 3 in worktree
    std::fs::write(&file1, "pub fn func_a() -> i32 { 42 }\n").unwrap();
    {
        let mut idx = wt_repo.index().unwrap();
        idx.add_path(Path::new("module_a.rs")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = wt_repo.find_tree(tree_oid).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        wt_repo.commit(Some("HEAD"), &sig, &sig, "feat: commit 3", &tree, &[&head]).unwrap();
    }

    // Add uncommitted leftover draft
    let draft_file = worktree_dir.join("scratch_ideas.txt");
    std::fs::write(&draft_file, "Uncommitted draft research notes\n").unwrap();

    // Execute squash_merge
    let merge_res = engine
        .squash_merge(
            &repo_path,
            &worktree_dir,
            &row.branch,
            "feat/hybrid-command-hub",
            "feat(modules): add module a and b\n\nCo-authored-by: Claude <noreply@anthropic.com>",
            Some("Human Lead"),
            Some("lead@company.internal"),
            &lease_id,
        )
        .await
        .expect("squash_merge failed");

    // 1. Verify leftover snapshot was archived
    assert!(merge_res.leftovers_ref.is_some());
    let leftovers_ref = merge_res.leftovers_ref.unwrap();
    let leftovers_commit = primary_repo
        .find_reference(&leftovers_ref)
        .expect("leftovers reference not found")
        .peel_to_commit()
        .unwrap();
    assert!(leftovers_commit.tree().unwrap().get_name("scratch_ideas.txt").is_some());

    // 2. Verify on base branch: exactly 1 squash commit on top of initial commit!
    let base_branch_ref = primary_repo
        .find_branch("feat/hybrid-command-hub", git2::BranchType::Local)
        .unwrap();
    let squash_commit = base_branch_ref.get().peel_to_commit().unwrap();

    assert_eq!(squash_commit.id().to_string(), merge_res.squash_commit_oid);
    // Exactly 1 parent!
    assert_eq!(squash_commit.parent_count(), 1);

    // Parent is the initial commit
    let parent = squash_commit.parent(0).unwrap();
    assert_eq!(parent.message().unwrap().trim(), "chore: initial base commit");

    // Check tree contains final state of module_a.rs and module_b.rs
    let squash_tree = squash_commit.tree().unwrap();
    assert!(squash_tree.get_name("module_a.rs").is_some());
    assert!(squash_tree.get_name("module_b.rs").is_some());

    // Verify commit message sanitized
    assert_eq!(squash_commit.message().unwrap().trim(), "feat(modules): add module a and b");

    // Verify worktree cleaned up
    assert!(!worktree_dir.exists());
    assert!(primary_repo.find_branch(&row.branch, git2::BranchType::Local).is_err());
}

/// F08 Test: Conflict detection when worktree conflicts with base branch.
#[tokio::test]
async fn challenge_f08_squash_merge_conflict_detection() {
    let temp_dir = tempfile::tempdir().expect("failed to create temp dir");
    let repo_path = temp_dir.path().to_path_buf();
    let primary_repo = init_test_git_repo(&repo_path);

    let engine = GitWorktreeEngine::new();
    let lease_id = "wt-conflict-1".to_string();

    let config = WorktreeConfig {
        lease_id: lease_id.clone(),
        repo_path: repo_path.clone(),
        base_branch: "feat/hybrid-command-hub".to_string(),
        room_id: Some("room-conflict".to_string()),
        team_id: Some("team-conflict".to_string()),
        owner_user_id: "challenger-2".to_string(),
    };

    let row = engine.allocate_worktree(config, None).await.expect("failed to allocate");
    let worktree_dir = PathBuf::from(&row.worktree_path);
    assert!(worktree_dir.exists());

    let wt_repo = git2::Repository::open(&worktree_dir).expect("failed to open worktree");
    let sig = git2::Signature::now("Challenger", "challenger@internal").unwrap();

    // 1. Advance base branch in primary repo by creating and committing a conflicting change
    let prim_readme = repo_path.join("README.md");
    std::fs::write(&prim_readme, "# Base Repo modified by upstream\nLine upstream\n").unwrap();
    {
        let mut idx = primary_repo.index().unwrap();
        idx.add_path(Path::new("README.md")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = primary_repo.find_tree(tree_oid).unwrap();
        let head = primary_repo.head().unwrap().peel_to_commit().unwrap();
        primary_repo.commit(Some("refs/heads/feat/hybrid-command-hub"), &sig, &sig, "chore: upstream conflict", &tree, &[&head]).unwrap();
    }

    // 2. Commit a conflicting change to README.md in the worktree
    let wt_readme = worktree_dir.join("README.md");
    std::fs::write(&wt_readme, "# Base Repo modified by worktree\nLine worktree divergent\n").unwrap();
    {
        let mut idx = wt_repo.index().unwrap();
        idx.add_path(Path::new("README.md")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = wt_repo.find_tree(tree_oid).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        wt_repo.commit(Some("HEAD"), &sig, &sig, "feat: divergent worktree edit", &tree, &[&head]).unwrap();
    }

    // 3. Attempt squash merge
    let result = engine
        .squash_merge(
            &repo_path,
            &worktree_dir,
            &row.branch,
            "feat/hybrid-command-hub",
            "feat: attempt merge conflicting edits",
            Some("Human Lead"),
            Some("lead@company.internal"),
            &lease_id,
        )
        .await;

    // 4. Assert that merge conflict is detected and returned
    match result {
        Err(WorktreeError::MergeConflict { conflicting_files }) => {
            println!("Correctly caught merge conflict in files: {:?}", conflicting_files);
            assert!(
                conflicting_files.iter().any(|f| f.contains("README.md")),
                "Expected README.md in conflicting files, got {:?}",
                conflicting_files
            );
        }
        other => panic!("Expected WorktreeError::MergeConflict, got: {:?}", other),
    }

    // 5. Worktree should NOT be deleted on conflict so user can resolve!
    assert!(worktree_dir.exists(), "Worktree directory should be preserved on conflict!");
}

#[tokio::test(flavor = "multi_thread", worker_threads = 8)]
async fn challenge_worktree_high_concurrency_and_lock_isolation() {
    use std::sync::Barrier;

    let temp_dir = tempfile::tempdir().expect("failed to create temp dir");
    let repo_path = temp_dir.path().to_path_buf();
    let _primary_repo = init_test_git_repo(&repo_path);

    let engine = std::sync::Arc::new(GitWorktreeEngine::new());
    let num_worktrees = 4;
    let mut rows = Vec::new();

    for i in 1..=num_worktrees {
        let lease_id = format!("wt-concurrent-{i}");
        let config = WorktreeConfig {
            lease_id: lease_id.clone(),
            repo_path: repo_path.clone(),
            base_branch: "feat/hybrid-command-hub".to_string(),
            room_id: Some("room-concurrent".to_string()),
            team_id: Some("team-concurrent".to_string()),
            owner_user_id: format!("user-{i}"),
        };
        let row = engine.allocate_worktree(config, None).await.expect("allocate failed");
        rows.push(row);
    }

    let barrier = std::sync::Arc::new(Barrier::new(num_worktrees + 1));
    let mut handles = Vec::new();

    // Spawn concurrent tasks for each worktree
    for (idx, row) in rows.iter().enumerate() {
        let wt_path = PathBuf::from(&row.worktree_path);
        let b = barrier.clone();
        let wt_idx = idx + 1;
        let handle = tokio::task::spawn_blocking(move || {
            let wt_repo = git2::Repository::open(&wt_path).expect("open worktree repo");
            let sig = git2::Signature::now(&format!("Worker-{wt_idx}"), "worker@test.internal").unwrap();

            b.wait();

            for c in 1..=5 {
                let filename = format!("wt_{wt_idx}_file_{c}.txt");
                let filepath = wt_path.join(&filename);
                std::fs::write(&filepath, format!("data from worktree {wt_idx} iteration {c}\n")).unwrap();

                let mut index = wt_repo.index().expect("open wt index");
                index.add_path(Path::new(&filename)).expect("add path to wt index");
                let tree_oid = index.write_tree().expect("write wt tree");
                let tree = wt_repo.find_tree(tree_oid).expect("find wt tree");
                let head = wt_repo.head().unwrap().peel_to_commit().unwrap();

                wt_repo
                    .commit(
                        Some("HEAD"),
                        &sig,
                        &sig,
                        &format!("feat: worktree {wt_idx} commit {c}"),
                        &tree,
                        &[&head],
                    )
                    .expect("commit in worktree failed");
            }
        });
        handles.push(handle);
    }

    // Main repo concurrently commits
    let main_repo_path = repo_path.clone();
    let b_main = barrier.clone();
    let main_handle = tokio::task::spawn_blocking(move || {
        let main_repo = git2::Repository::open(&main_repo_path).expect("open main repo");
        let sig = git2::Signature::now("MainDev", "main@test.internal").unwrap();

        b_main.wait();

        for c in 1..=5 {
            let filename = format!("main_concurrent_file_{c}.txt");
            let filepath = main_repo_path.join(&filename);
            std::fs::write(&filepath, format!("data from main iteration {c}\n")).unwrap();

            let mut index = main_repo.index().expect("open main index");
            index.add_path(Path::new(&filename)).expect("add path to main index");
            let tree_oid = index.write_tree().expect("write main tree");
            let tree = main_repo.find_tree(tree_oid).expect("find main tree");
            let head = main_repo.head().unwrap().peel_to_commit().unwrap();

            main_repo
                .commit(
                    Some("HEAD"),
                    &sig,
                    &sig,
                    &format!("chore: main commit {c}"),
                    &tree,
                    &[&head],
                )
                .expect("commit in main repo failed");
        }
    });

    for h in handles {
        h.await.expect("worktree worker task panicked");
    }
    main_handle.await.expect("main worker task panicked");

    // Verify all worktrees have their commits intact
    for (idx, row) in rows.iter().enumerate() {
        let wt_idx = idx + 1;
        let wt_path = PathBuf::from(&row.worktree_path);
        let wt_repo = git2::Repository::open(&wt_path).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        assert_eq!(head.message().unwrap(), &format!("feat: worktree {wt_idx} commit 5"));

        // Verify diff computation concurrently works
        let diff = engine
            .compute_diff(&repo_path, &wt_path, "feat/hybrid-command-hub", &row.lease_id)
            .await
            .unwrap();
        println!("Worktree {wt_idx} diff: files_changed={}, patch:\n{}", diff.files_changed, diff.patch);
        assert!(diff.files_changed >= 5);
        assert!(diff.patch.contains(&format!("wt_{wt_idx}_file_1.txt")));
        assert!(diff.patch.contains(&format!("wt_{wt_idx}_file_5.txt")));
    }
}

#[tokio::test]
