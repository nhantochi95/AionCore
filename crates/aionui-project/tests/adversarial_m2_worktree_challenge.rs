/// F08 Test: Non-conflicting divergent base branch merge
#[tokio::test]
async fn challenge_f08_squash_merge_non_conflicting_divergent_base() {
    let temp_dir = tempfile::tempdir().expect("failed to create temp dir");
    let repo_path = temp_dir.path().to_path_buf();
    let primary_repo = init_test_git_repo(&repo_path);

    let engine = GitWorktreeEngine::new();
    let lease_id = "wt-divergent-ok-1".to_string();

    let config = WorktreeConfig {
        lease_id: lease_id.clone(),
        repo_path: repo_path.clone(),
        base_branch: "feat/hybrid-command-hub".to_string(),
        room_id: Some("room-div".to_string()),
        team_id: Some("team-div".to_string()),
        owner_user_id: "challenger-3".to_string(),
    };

    let row = engine.allocate_worktree(config, None).await.expect("failed to allocate");
    let worktree_dir = PathBuf::from(&row.worktree_path);

    let wt_repo = git2::Repository::open(&worktree_dir).expect("failed to open worktree");
    let sig = git2::Signature::now("Challenger", "challenger@internal").unwrap();

    // 1. Advance base branch in primary repo by committing a DIFFERENT file (other_file.txt)
    let prim_other = repo_path.join("other_file.txt");
    std::fs::write(&prim_other, "content in primary repo\n").unwrap();
    {
        let mut idx = primary_repo.index().unwrap();
        idx.add_path(Path::new("other_file.txt")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = primary_repo.find_tree(tree_oid).unwrap();
        let head = primary_repo.head().unwrap().peel_to_commit().unwrap();
        primary_repo.commit(Some("refs/heads/feat/hybrid-command-hub"), &sig, &sig, "chore: upstream other file", &tree, &[&head]).unwrap();
    }

    // 2. Commit agent file in worktree
    let wt_agent = worktree_dir.join("agent_feature.txt");
    std::fs::write(&wt_agent, "feature from agent\n").unwrap();
    {
        let mut idx = wt_repo.index().unwrap();
        idx.add_path(Path::new("agent_feature.txt")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = wt_repo.find_tree(tree_oid).unwrap();
        let head = wt_repo.head().unwrap().peel_to_commit().unwrap();
        wt_repo.commit(Some("HEAD"), &sig, &sig, "feat: agent feature", &tree, &[&head]).unwrap();
    }

    // 3. Attempt squash merge - should succeed and merge both other_file.txt and agent_feature.txt
    let merge_res = engine
        .squash_merge(
            &repo_path,
            &worktree_dir,
            &row.branch,
            "feat/hybrid-command-hub",
            "feat(sync): merge non conflicting feature",
            Some("Human Lead"),
            Some("lead@company.internal"),
            &lease_id,
        )
        .await
        .expect("squash_merge of non-conflicting divergence failed");

    // 4. Verify base branch has both files!
    let base_branch_ref = primary_repo
        .find_branch("feat/hybrid-command-hub", git2::BranchType::Local)
        .unwrap();
    let squash_commit = base_branch_ref.get().peel_to_commit().unwrap();
    assert_eq!(squash_commit.id().to_string(), merge_res.squash_commit_oid);
    let tree = squash_commit.tree().unwrap();
    assert!(tree.get_name("other_file.txt").is_some());
    assert!(tree.get_name("agent_feature.txt").is_some());
    assert!(tree.get_name("README.md").is_some());
}
