    let temp_dir = tempfile::tempdir().expect("failed to create temp dir");
    let repo_path = temp_dir.path().to_path_buf();
    let primary_repo = init_test_git_repo(&repo_path);

    // Add baseline tracked files to feat/hybrid-command-hub
    let to_modify_path = repo_path.join("tracked_to_modify.txt");
    let to_delete_path = repo_path.join("tracked_to_delete.txt");
    std::fs::write(&to_modify_path, "original content before modify\n").unwrap();
    std::fs::write(&to_delete_path, "original content before delete\n").unwrap();

    let sig = git2::Signature::now("Challenger", "challenger@internal").unwrap();
    {
        let mut idx = primary_repo.index().unwrap();
        idx.add_path(Path::new("tracked_to_modify.txt")).unwrap();
        idx.add_path(Path::new("tracked_to_delete.txt")).unwrap();
        let tree_oid = idx.write_tree().unwrap();
        let tree = primary_repo.find_tree(tree_oid).unwrap();
        let head = primary_repo.head().unwrap().peel_to_commit().unwrap();
        primary_repo
            .commit(
                Some("HEAD"),
                &sig,
                &sig,
                "chore: add initial tracked files",
                &tree,
                &[&head],
            )
            .unwrap();
    }

    let engine = GitWorktreeEngine::new();
    let lease_id = "wt-leftovers-adv-1".to_string();

    let config = WorktreeConfig {
        lease_id: lease_id.clone(),
        repo_path: repo_path.clone(),
        base_branch: "feat/hybrid-command-hub".to_string(),
        room_id: Some("room-leftovers".to_string()),
        team_id: Some("team-leftovers".to_string()),
        owner_user_id: "challenger-leftovers".to_string(),
    };

    let row = engine.allocate_worktree(config, None).await.expect("failed to allocate");
    let worktree_dir = PathBuf::from(&row.worktree_path);

    // 1. Untracked root text file
    let draft_txt = worktree_dir.join("draft_notes.txt");
    let draft_txt_content = "agent draft notes: priority alpha\n";
    std::fs::write(&draft_txt, draft_txt_content).unwrap();

    // 2. Untracked binary file
    let bin_path = worktree_dir.join("artifact.bin");
    let bin_bytes: Vec<u8> = vec![0x00, 0xFF, 0x00, 0x80, 0xFE, 0x12, 0x34, 0x56, 0x78, 0xAA, 0x55];
    std::fs::write(&bin_path, &bin_bytes).unwrap();

    // 3. Deeply nested uncommitted file
    let nested_dir = worktree_dir.join("deeply").join("nested").join("sub").join("path");
    std::fs::create_dir_all(&nested_dir).unwrap();
    let nested_txt = nested_dir.join("design_spec.md");
    let nested_txt_content = "# Highly Nested Uncommitted Spec\nDetailed architecture notes.\n";
    std::fs::write(&nested_txt, nested_txt_content).unwrap();

    // 4. Deeply nested binary file
    let nested_bin = nested_dir.join("nested_blob.bin");
    let nested_bin_bytes: Vec<u8> = vec![0xCA, 0xFE, 0xBA, 0xBE, 0x00, 0x01, 0x02, 0x03];
    std::fs::write(&nested_bin, &nested_bin_bytes).unwrap();

    // 5. Dirty edits on tracked file (uncommitted edit)
    let wt_to_modify = worktree_dir.join("tracked_to_modify.txt");
    let modified_content = "MODIFIED dirty uncommitted edits by agent\n";
    std::fs::write(&wt_to_modify, modified_content).unwrap();

    // 6. Deleted tracked file (uncommitted deletion)
    let wt_to_delete = worktree_dir.join("tracked_to_delete.txt");
    std::fs::remove_file(&wt_to_delete).unwrap();

    // 7. Empty draft file (0 bytes)
    let empty_file = worktree_dir.join("empty_draft.txt");
    std::fs::write(&empty_file, b"").unwrap();

    // 8. Untracked dotfile in root
    let dotfile = worktree_dir.join(".env.draft");
    let dotfile_content = "SECRET_TOKEN=super_secret_value\n";
    std::fs::write(&dotfile, dotfile_content).unwrap();

    // 9. Nested dotfile in dotdir
    let dotdir = worktree_dir.join(".internal_state");
    std::fs::create_dir_all(&dotdir).unwrap();
    let dotdir_file = dotdir.join(".cached_session.json");
    let dotdir_content = "{\"session\": 999}\n";
    std::fs::write(&dotdir_file, dotdir_content).unwrap();

    // Discard worktree - this triggers archive_leftovers and then teardown_directory!
    let leftovers_ref = engine
        .discard_worktree(
            &repo_path,
            &worktree_dir,
            &row.branch,
            &lease_id,
        )
        .await
        .expect("discard_worktree failed");

    // Verification 1: leftovers_ref must be Some
    assert!(leftovers_ref.is_some(), "leftovers_ref must be created when uncommitted drafts exist!");
    let ref_name = leftovers_ref.unwrap();
    println!("Created leftovers ref: {ref_name}");
    assert!(ref_name.starts_with(&format!("refs/aionui/leftovers/{lease_id}_")));

    // Verification 2: Reference exists in primary repo object database
    let leftovers_ref_obj = primary_repo.find_reference(&ref_name).expect("leftovers reference not found in primary repo");
    let leftovers_commit = leftovers_ref_obj.peel_to_commit().expect("peel to leftovers commit failed");
    let tree = leftovers_commit.tree().expect("find leftovers tree failed");

    // Helper closure to read file content from tree path
    let read_tree_file = |path_str: &str| -> Option<Vec<u8>> {
        let entry = tree.get_path(Path::new(path_str)).ok()?;
        let obj = entry.to_object(&primary_repo).ok()?;
        let blob = obj.into_blob().ok()?;
        Some(blob.content().to_vec())
    };

    // Check 1: draft_notes.txt
    let draft_data = read_tree_file("draft_notes.txt");
    assert!(draft_data.is_some(), "draft_notes.txt was NOT preserved in leftovers!");
    assert_eq!(draft_data.unwrap(), draft_txt_content.as_bytes());

    // Check 2: artifact.bin
    let bin_data = read_tree_file("artifact.bin");
    assert!(bin_data.is_some(), "artifact.bin was NOT preserved in leftovers!");
    assert_eq!(bin_data.unwrap(), bin_bytes);

    // Check 3: deeply/nested/sub/path/design_spec.md
    let nested_data = read_tree_file("deeply/nested/sub/path/design_spec.md");
    assert!(nested_data.is_some(), "nested design_spec.md was NOT preserved in leftovers!");
    assert_eq!(nested_data.unwrap(), nested_txt_content.as_bytes());

    // Check 4: deeply/nested/sub/path/nested_blob.bin
